#!/usr/bin/env python3
"""
Generates the OpenAPI schema, EvoMaster auth config and labels of each cell
of the scaling grid (final project), from cases/final_scaling_app/plan.py.

    python3 scripts/final_gen_scaling.py            # default grid E 5,10,20,40 x U 2,4,8
    python3 scripts/final_gen_scaling.py 10 4       # one cell

Output: cases/final_scaling/E<e>_U<u>/{openapi.json, em.yaml, labels.json}.
Standard library only.
"""

import json
import os
import sys

REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(REPO_ROOT, "cases", "final_scaling_app"))
import plan  # noqa: E402

GRID_E = (5, 10, 20, 40)
GRID_U = (2, 4, 8)
OUT_ROOT = os.path.join(REPO_ROOT, "cases", "final_scaling")


def schema(e, u):
    id_param = [{"name": "id", "in": "path", "required": True,
                 "schema": {"type": "integer", "format": "int32"}}]
    status = {"201": {"description": "Created"}, "204": {"description": "Updated"},
              "400": {"description": "Bad request"}, "401": {"description": "Not authenticated"},
              "403": {"description": "Forbidden"}}
    paths = {"/api/resources/{id}": {
        "put": {"operationId": "put", "parameters": id_param, "responses": status},
        "get": {"operationId": "get", "parameters": id_param, "responses": {
            "200": {"description": "The user who created the resource",
                    "content": {"text/plain": {"schema": {"type": "string"}}}},
            "400": {"description": "Bad request"}, "401": {"description": "Not authenticated"},
            "403": {"description": "Forbidden"}}}}}
    for i, path, kind in plan.endpoints(e):
        op = {"operationId": f"e{i}", "responses": {
            "200": {"description": "OK", "content": {"application/json": {"schema": {"type": "object"}}}},
            "401": {"description": "Not authenticated"}}}
        if kind == "second":
            op["parameters"] = [{"name": "X-Api-Key", "in": "header", "required": True,
                                 "schema": {"type": "string"}}]
        paths[path] = {"get": op}
    return {"openapi": "3.0.3",
            "info": {"title": f"Generated scaling API, E={e} protected endpoints, U={u} users",
                     "version": "1.0"},
            "servers": [{"url": "http://localhost:8084"}],
            "paths": paths}


def auth_config(u):
    lines = ["# EvoMaster auth config (generated by scripts/final_gen_scaling.py):",
             "# users identified by a fixed Authorization header.", "auth:"]
    for name in plan.users(u):
        lines += [f"  - name: {name}", "    fixedHeaders:", "      - name: Authorization",
                  f"        value: {name}"]
    return "\n".join(lines) + "\n"


def labels(e, u):
    return {"E": e, "U": u, "users": plan.users(u),
            "endpoints": [{"operation": f"GET:{p}", "kind": k} for _, p, k in plan.endpoints(e)],
            "expected_not_recognized": plan.expected_faults(e)}


def write_cell(e, u):
    out = os.path.join(OUT_ROOT, f"E{e}_U{u}")
    os.makedirs(out, exist_ok=True)
    with open(os.path.join(out, "openapi.json"), "w") as f:
        json.dump(schema(e, u), f, indent=2)
        f.write("\n")
    with open(os.path.join(out, "em.yaml"), "w") as f:
        f.write(auth_config(u))
    with open(os.path.join(out, "labels.json"), "w") as f:
        json.dump(labels(e, u), f, indent=2)
        f.write("\n")
    return out


def main(argv):
    cells = [(int(argv[0]), int(argv[1]))] if len(argv) == 2 else [(e, u) for e in GRID_E for u in GRID_U]
    for e, u in cells:
        print(write_cell(e, u))


if __name__ == "__main__":
    main(sys.argv[1:])
